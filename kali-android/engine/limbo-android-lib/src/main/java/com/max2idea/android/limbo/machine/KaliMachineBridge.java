package com.max2idea.android.limbo.machine;
import com.kp.kali.core.VmConfig;
public final class KaliMachineBridge {
    private KaliMachineBridge() {}
    public static void prepareManaged(VmConfig config){
        prepare("", "raw", config);
        MachineController.getInstance().getMachine().setExtraParams("");
    }
    public static void prepare(String disk, String format, VmConfig config) {
        Machine m=new Machine("Kali",false);
        m.setArch("x86");m.setMachineType("pc");m.setCpu("qemu64");m.setCpuNum(config.cpus);
        m.setMemory(config.memoryMiB);m.setEnableKVM(0);m.setEnableMTTCG(1);m.setDisableTSC(0);
        m.setEnableVNC(0);m.setBootDevice("Hard Disk");m.setVga("std");m.setNetwork("User");m.setNetworkCard("e1000");
        // Fixed private path generated by the app; explicit format prevents raw-disk probing restrictions.
        m.setExtraParams("-drive file="+disk+",format="+format+",if=ide,index=0");
        MachineController.getInstance().setMachine(m);
    }
}
